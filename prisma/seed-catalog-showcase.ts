/** Delivery at home at one flat rate, and everywhere else at another. */
function zones(
  home: { name: string; countries: string[]; priceCents: number; days: [number, number] },
  worldCents: number,
): SeedZone[] {
  return [
    {
      name: home.name,
      countries: home.countries,
      rates: [{ name: "Standard", priceCents: home.priceCents, days: home.days }],
    },
    {
      name: "Rest of world",
      restOfWorld: true,
      countries: [],
      rates: [{ name: "International", priceCents: worldCents, days: [7, 21] }],
    },
  ];
}

/** One option, as most of these products have. */
function single(sku: string, priceCents: number, inventoryQty: number): SeedProduct["variants"] {
  return [{ title: "Default", sku, priceCents, inventoryQty }];
}

